"""PULSE loss map — where the model loses money, sliced by decision state.

    .venv/bin/python analysis/pulse_loss_map.py [--tape CSV] [--ledger CSV]
    .venv/bin/python analysis/pulse_loss_map.py --selftest

Reads the exported decision tape (pin: ``20260901T195202Z``), reconstructs
the entry-level round-trip ledger exactly per ``core/pulse/live_report.py``'s
conventions, and prints a markdown loss map: per-$ outcomes cut by market
type, estimator version, the depth axis (price band), game state, spread and
claimed edge. Written to the 2026-09-01 wave standard
(``analysis/WAVE_STANDARD.md``).

EVERYTHING HERE IS DESCRIPTIVE AND IN-SAMPLE — hypothesis-generating, never
gating. Standing caveats on every cell:

1. **Fill-rule optimism** (docs/math/pulse-live.md): a shadow fill happens
   when a newer mid crosses the resting price. Losses are trustworthy;
   profits are upper bounds — doubled on round trips (two optimistic fills).
   A pessimistic arm re-scores fills with the measured in-game concession
   (4.70¢ per filled quote, E[−dmid | fill], docs/findings.md C13 —
   measured on the QUOTE study's 30s windows; the regime mismatch with
   PULSE's resting limits is stated, not hidden).
2. **Clusters are games, not rows** (docs/math/clustered-errors.md). Every
   interval below is game-clustered via the one blessed implementation.
3. **Multiplicity**: the script counts every interval it computes and prints
   the total. At 95%, one in twenty is expected significant by chance.

Population note (the 2026-08-23 ruling in docs/math/pulse-live.md): rows with
``capped_stake_usd = 0`` are cap-blocked intents — annotations, not trades.
They belong only to the FULL-INTENT population, which is where nearly all of
this tape lives (the shadow engine annotates instead of blocking). The
live-faithful subset is reported separately, unsliced — far too small to
cut. Dollar sums over full-intent rows are SHADOW dollars at the model's
desired size, never money live would have committed.

Scoring policy (ONE definition, labelled): maker fee Θ=0 on both legs
(docs/math/fees-and-spread.md — resting limits, no taker path), so gross =
net here.

* round trip  — per-$ = capture / cost, capture in the position's direction
* ride        — per-$ = returned / staked − 1, money at price (C11/V14)
* pooled      — each filled entry contributes its one realized per-$ outcome
  (trip capture if its exit filled, ride ROI otherwise). Pooling legs is a
  map convenience; the legs are also shown split, because their evidence
  quality differs (the trip leg is optimistic twice).

The substrate is Quant A's round-trip ledger
(``backups/exports/roundtrip_ledger_20260901T195202Z.csv``, regenerated by
``analysis/roundtrip_ledger.py`` — wave standard rule 4: one P&L definition,
mutation-tested, venue-reconciled). This script reconciles its own
tape reconstruction against A's ledger and reports every divergence; when the
ledger file is absent it falls back to the reconstruction so the map stays
reproducible from the pinned tape alone. A's ``lineage_source =
'reconstructed'`` rows (17 early-era orphan exits re-linked by A's stated
rule) are CARRIED, shifting those entries from ride to trip relative to the
raw reconstruction; the reconciliation prints the count.
"""

